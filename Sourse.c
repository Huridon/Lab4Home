#include <stdio.h>

int main() {
    int A, B, C;
    int condition;
    // Сообщаем пользователю, что делает программа
    printf("=== КОНТРОЛЬ КАЧЕСТВА ИГРУШЕК ===\n");
    printf("Введите вес трех игрушек (A, B, C): ");
    // Считываем вес игрушек
    scanf("%d %d %d", &A, &B, &C);
    // Проверяем, кратен ли вес каждой игрушки семи
    condition = (A % 7 == 0) && (B % 7 == 0) && (C % 7 == 0);
    printf("Партия принята (1 - да, 0 - нет): %d\n", condition);
    return 0;
}
